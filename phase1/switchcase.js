// switch is used when there are multiple case can happen
let num =3;
switch(num){
    case 1:
        console.log("1");
        break;
    case 2:
        console.log("2");
        break;
    case 3:
        console.log("3");
        break;
    default:
        console.log("defualt");
}   

// there is a specila case like if we forget to use break in case and the case passed then after that passed case the remaininig case also printed